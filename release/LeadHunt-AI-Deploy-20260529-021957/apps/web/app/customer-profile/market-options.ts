const zhRegionNames = new Intl.DisplayNames(["zh-CN"], { type: "region" });
const enRegionNames = new Intl.DisplayNames(["en"], { type: "region" });

const countryMarketOptions: MarketOption[] = regionCodes
  .map((code) => {
    const label = zhNameOverrides[code] ?? zhRegionNames.of(code) ?? code;
    const value = enNameOverrides[code] ?? enRegionNames.of(code) ?? code;

    return {
      value,
      label,
      group: "country" as const,
      aliases: [code, value]
    };
  })
  .sort((left, right) => left.label.localeCompare(right.label, "zh-CN"));

export const MARKET_OPTIONS: MarketOption[] = [...macroMarketOptions, ...countryMarketOptions];

export const marketOptionByValue = new Map(MARKET_OPTIONS.map((option) => [option.value, option]));

export function getMarketLabel(value: string) {
  return marketOptionByValue.get(value)?.label ?? value;
}
